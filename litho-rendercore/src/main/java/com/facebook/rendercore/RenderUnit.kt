@file:Suppress("UNCHECKED_CAST")

package com.facebook.rendercore

import android.content.Context
import android.util.SparseArray
import androidx.annotation.IdRes
import androidx.annotation.VisibleForTesting
import androidx.collection.MutableScatterMap
import androidx.collection.MutableScatterSet
import androidx.collection.ScatterMap
import androidx.collection.ScatterSet
import androidx.collection.emptyScatterSet
import com.facebook.rendercore.extensions.ExtensionState
import com.facebook.rendercore.utils.CommonUtils.getSectionNameForTracing

/**
 * A RenderUnit represents a single rendering primitive for RenderCore. Every RenderUnit has to
 * define at least a createContent method to allocate the RenderUnit content (View or Drawable) via
 * the [ContentAllocator] it returns from getContentAllocator method. That content will be
 * automatically recycled by RenderCore based on their concrete type.
 *
 * A RenderUnit should in most cases declare how it intends to bind data returning Binders from its
 * mountUnmountFunctions callback or from the attachDetachFunctions callback.
 *
 * Immutability: RenderUnits should be immutable! Continuing to change them after they are built and
 * given to RenderCore (e.g. via RenderState) is not safe.
 */
abstract class RenderUnit<MOUNT_CONTENT : Any>
@JvmOverloads
constructor(
    fixedMountBinders: List<DelegateBinder<*, in MOUNT_CONTENT, *>>? = null,
    optionalMountBinders: List<DelegateBinder<*, in MOUNT_CONTENT, *>> = emptyList(),
    attachBinders: List<DelegateBinder<*, in MOUNT_CONTENT, *>> = emptyList(),
    extras: SparseArray<Any?>? = null,
) {

  open val renderType: RenderType
    get() = contentAllocator.renderType

  // These maps are used to match a binder with its Binder class.
  // Every RenderUnit should have only one Binder per type.
  private var optionalMountBinderKeyToDelegateMap: MutableScatterMap<BinderKey, BinderHolder>? =
      null
  private var optionalMountBinders: MutableList<BinderHolder>? = null

  // Fixed mount binders are binders that are always there for a given RenderUnit type, and they're
  // always in the same order.
  private val fixedMountBinders: List<BinderHolder>?
  private var attachBinderKeyToDelegateMap: MutableScatterMap<BinderKey, BinderHolder>? = null
  private var attachBinders: MutableList<BinderHolder>? = null

  // Extra data associated with RenderUnit.
  // The keys must be unique integers generated by Android resource ID system (via XML).
  private var extras: SparseArray<Any?>? = null
  private val continuationInfo = ContinuationInfo()

  init {
    check(!(fixedMountBinders != null && fixedMountBinders.size > MAX_FIXED_MOUNT_BINDERS_COUNT)) {
      "Too many fixed mount binders. Max is $MAX_FIXED_MOUNT_BINDERS_COUNT"
    }
    this.fixedMountBinders = createFixedBinders(this, fixedMountBinders)
    for (i in optionalMountBinders.indices) {
      val binder = optionalMountBinders[i]
      addOptionalMountBinder(binder)
    }
    for (i in attachBinders.indices) {
      val binder = attachBinders[i]
      addAttachBinder(binder)
    }
    if (extras != null && extras.size() > 0) {
      this.extras = extras.clone()
    }
  }

  abstract val contentAllocator: ContentAllocator<MOUNT_CONTENT>

  /** @return a unique id identifying this RenderUnit in the tree of Node it is part of. */
  abstract val id: Long
  open val debugKey: String?
    /** Returns a key that can be used for debugging purposes. */
    get() = id.toString()

  open fun onStartUpdateRenderUnit(): Unit = Unit

  open fun onEndUpdateRenderUnit(): Unit = Unit

  open val description: String
    get() = getSectionNameForTracing(javaClass)

  /** Returns extra data associated with this RenderUnit for given key. */
  open fun <T> getExtra(@IdRes key: Int): T? {
    return extras?.get(key) as T?
  }

  /**
   * Fast path check to determine if this [RenderUnit] has any continuations to restart during mount
   */
  @VisibleForTesting(otherwise = VisibleForTesting.PACKAGE_PRIVATE)
  internal fun hasAnyContinuations(): Boolean = continuationInfo.hasAnyContinuations()

  /**
   * Whether any of this render unit's continuations have a newer value in the store than they last
   * applied (so a restart would actually do work). See [BinderHolder.hasNewContinuationValues].
   */
  internal fun hasNewContinuationValues(context: MountContinuationContext): Boolean =
      continuationInfo.hasNewContinuationValues(context)

  /**
   * Runs all continuations that any binders of this render unit has within the scope of the given
   * [MountContinuationContext]
   */
  internal fun restartContinuations(context: MountContinuationContext) {
    continuationInfo.restartContinuations(context)
  }

  /**
   * Adds an [DelegateBinder] that will be invoked with the other mount/unmount binders. Can be used
   * to add generic functionality (e.g. accessibility) to a RenderUnit.
   *
   * NB: This method should only be called while initially configuring the RenderUnit. See the
   * class-level javadocs about immutability.
   */
  open fun addOptionalMountBinder(binder: DelegateBinder<*, in MOUNT_CONTENT, *>) {
    val mountBinders = optionalMountBinders ?: ArrayList()
    val needsInit = optionalMountBinders == null
    if (needsInit) {
      optionalMountBinders = mountBinders
    }
    if (needsInit) {
      check(optionalMountBinderKeyToDelegateMap == null) {
        "Binder Map and Binder List out of sync!"
      }
      optionalMountBinderKeyToDelegateMap = MutableScatterMap()
    }
    optionalMountBinderKeyToDelegateMap?.let {
      addBinder(it, mountBinders, binder, this, BinderType.MOUNT)
    }
  }

  /**
   * Adds [DelegateBinder]s that will be invoked with the other mount/unmount binders. Can be used
   * to add generic functionality (e.g. accessibility) to a RenderUnit.
   *
   * NB: This method should only be called while initially configuring the RenderUnit. See the
   * class-level javadocs about immutability.
   */
  @SafeVarargs
  fun addOptionalMountBinders(vararg binders: DelegateBinder<*, in MOUNT_CONTENT, *>) {
    for (i in binders.indices) {
      addOptionalMountBinder(binders[i])
    }
  }

  /**
   * Adds an [DelegateBinder] that will be invoked with the other attach/detach binders. Can be used
   * to add generic functionality (e.g. Dynamic Props) to a RenderUnit
   *
   * NB: This method should only be called while initially configuring the RenderUnit. See the
   * class-level javadocs about immutability.
   */
  open fun addAttachBinder(binder: DelegateBinder<*, in MOUNT_CONTENT, *>) {
    val binders = attachBinders ?: ArrayList()
    val needsInit = attachBinders == null
    if (needsInit) {
      attachBinders = binders
    }
    if (needsInit) {
      check(attachBinderKeyToDelegateMap == null) { "Binder Map and Binder List out of sync!" }
      attachBinderKeyToDelegateMap = MutableScatterMap()
    }
    attachBinderKeyToDelegateMap?.let { addBinder(it, binders, binder, this, BinderType.ATTACH) }
  }

  /**
   * Adds an [DelegateBinder]s that will be invoked with the other attach/detach binders. Can be
   * used to add generic functionality (e.g. Dynamic Props) to a RenderUnit
   *
   * NB: This method should only be called while initially configuring the RenderUnit. See the
   * class-level javadocs about immutability.
   */
  @SafeVarargs
  fun addAttachBinders(vararg binders: DelegateBinder<*, in MOUNT_CONTENT, *>) {
    for (i in binders.indices) {
      addAttachBinder(binders[i])
    }
  }

  /**
   * Override this method to indicate if a [RenderUnit] has nested [RenderTreeHost]s, it will ensure
   * that they are notified when this [RenderUnit]'s bounds change and visibility events are
   * processed correctly for them.
   *
   * @return `true` to ensure nested [RenderTreeHost]s are notified about parent's bounds change,
   *   otherwise `false`
   */
  open fun doesMountRenderTreeHosts(): Boolean {
    return false
  }

  /** Bind all mountUnmount binder functions. */
  open fun mountBinders(
      context: MountContext,
      content: MOUNT_CONTENT,
      layoutData: Any?,
      bindData: BindData,
  ) {
    mountFixedBinders(context, content, layoutData, bindData)
    mountOptionalBinders(context, content, layoutData, bindData)
  }

  /** Bind all fixed mountUnmount binder functions. */
  private fun mountFixedBinders(
      context: MountContext,
      content: MOUNT_CONTENT,
      layoutData: Any?,
      bindData: BindData,
  ) {
    val tracer = context.tracer
    val isTracing = tracer.isTracing()
    val fixedMountBindersSize = fixedMountBinders?.size ?: return
    if (isTracing) {
      tracer.beginSection(sectionName("$description:mount-fixed"))
    }

    for (i in 0 until fixedMountBindersSize) {
      val holder = fixedMountBinders[i]
      if (isTracing) {
        tracer.beginSection(sectionName(holder.binder.description))
      }
      try {
        val binderBindData = holder.bind(context, content, layoutData)
        bindData.setFixedBindersBindData(binderBindData, i, fixedMountBindersSize)
      } catch (exception: Exception) {
        throw RenderUnitOperationException(
            renderUnit = this,
            message = "Exception binding fixed mount binder: ${holder.binder.description}",
            cause = exception,
        )
      } finally {
        if (isTracing) {
          tracer.endSection()
        }
      }
    }

    if (isTracing) {
      tracer.endSection()
    }
  }

  private fun mountOptionalBinders(
      context: MountContext,
      content: MOUNT_CONTENT,
      layoutData: Any?,
      bindData: BindData,
  ) {
    val tracer = context.tracer
    val optionalMountBinders = optionalMountBinders
    val isTracing = tracer.isTracing()
    val optionalMountBindersSize = optionalMountBinders?.size ?: return
    if (isTracing) {
      tracer.beginSection(sectionName("$description:mount-optional"))
    }
    for (i in 0 until optionalMountBindersSize) {
      val holder = optionalMountBinders[i]
      if (isTracing) {
        tracer.beginSection(sectionName(holder.binder.description))
      }

      try {
        val binderBindData = holder.bind(context, content, layoutData)
        bindData.setOptionalMountBindersBindData(
            binderBindData,
            holder.binderKey,
            optionalMountBindersSize,
        )
      } catch (exception: Exception) {
        throw RenderUnitOperationException(
            renderUnit = this,
            message =
                "Exception while mounting optional mount binder: ${holder.binder.description}",
            cause = exception,
        )
      } finally {
        if (isTracing) {
          tracer.endSection()
        }
      }
    }
    if (isTracing) {
      tracer.endSection()
    }
  }

  /** Unbind all mountUnmount binder functions. */
  open fun unmountBinders(
      context: MountContext,
      content: MOUNT_CONTENT,
      layoutData: Any?,
      bindData: BindData,
  ) {
    unmountOptionalBinders(context, content, layoutData, bindData)
    unmountFixedBinders(context, content, layoutData, bindData)
  }

  private fun unmountOptionalBinders(
      context: MountContext,
      content: MOUNT_CONTENT,
      layoutData: Any?,
      bindData: BindData,
  ) {
    val tracer = context.tracer
    optionalMountBinders?.let { optionalMountBinders ->
      val isTracing = tracer.isTracing()
      if (isTracing) {
        tracer.beginSection(sectionName("$description:unmount-optional"))
      }
      for (i in optionalMountBinders.indices.reversed()) {
        val holder = optionalMountBinders[i]
        if (isTracing) {
          tracer.beginSection(sectionName(holder.binder.description))
        }

        try {
          holder.unbind(
              context,
              content,
              layoutData,
              bindData.removeOptionalMountBindersBindData(holder.binderKey),
          )
        } catch (exception: Exception) {
          throw RenderUnitOperationException(
              renderUnit = this,
              message =
                  "Exception while unmounting optional binder: [$description] ${holder.binder.description}",
              cause = exception,
          )
        } finally {
          if (isTracing) {
            tracer.endSection()
          }
        }
      }
      if (isTracing) {
        tracer.endSection()
      }
    }
  }

  /** Unbind all fixed mountUnmount binder functions. */
  private fun unmountFixedBinders(
      context: MountContext,
      content: MOUNT_CONTENT,
      layoutData: Any?,
      bindData: BindData,
  ) {
    val tracer = context.tracer
    val isTracing = tracer.isTracing()
    fixedMountBinders ?: return
    if (isTracing) {
      tracer.beginSection(sectionName("$description:unmount-fixed"))
    }
    for (i in fixedMountBinders.indices.reversed()) {
      val holder = fixedMountBinders[i]
      if (isTracing) {
        tracer.beginSection(sectionName(holder.binder.description))
      }
      try {
        holder.unbind(context, content, layoutData, bindData.removeFixedBinderBindData(i))
      } catch (exception: Exception) {
        throw RenderUnitOperationException(
            renderUnit = this,
            message = "Exception while unmounting fixed binder: ${holder.binder.description}",
            cause = exception,
        )
      } finally {
        if (isTracing) {
          tracer.endSection()
        }
      }
    }
    if (isTracing) {
      tracer.endSection()
    }
  }

  /** Bind all attachDetach binder functions. */
  open fun attachBinders(
      context: MountContext,
      content: MOUNT_CONTENT,
      layoutData: Any?,
      bindData: BindData,
  ) {
    val tracer = context.tracer
    val attachBinders = attachBinders ?: return
    val isTracing = tracer.isTracing()
    val attachBindersSize = attachBinders.size
    if (isTracing) {
      tracer.beginSection(sectionName("$description:attach"))
    }
    for (i in 0 until attachBindersSize) {
      val holder = attachBinders[i]
      if (isTracing) {
        tracer.beginSection(sectionName(holder.binder.description))
      }
      val binderBindData = holder.bind(context, content, layoutData)
      bindData.setAttachBindersBindData(binderBindData, holder.binderKey, attachBindersSize)
      if (isTracing) {
        tracer.endSection()
      }
    }
    if (isTracing) {
      tracer.endSection()
    }
  }

  /** Unbind all attachDetach binder functions. */
  open fun detachBinders(
      context: MountContext,
      content: MOUNT_CONTENT,
      layoutData: Any?,
      bindData: BindData,
  ) {
    val tracer = context.tracer
    val attachBinders = attachBinders ?: return
    val isTracing = tracer.isTracing()
    if (isTracing) {
      tracer.beginSection(sectionName("$description:detach"))
    }
    for (i in attachBinders.indices.reversed()) {
      val holder = attachBinders[i]
      if (isTracing) {
        tracer.beginSection(sectionName(holder.binder.description))
      }
      holder.unbind(
          context,
          content,
          layoutData,
          bindData.removeAttachBindersBindData(holder.binderKey),
      )
      if (isTracing) {
        tracer.endSection()
      }
    }
    if (isTracing) {
      tracer.endSection()
    }
  }

  /** Retrieve the specific [Binder] with the given [binderId] and update it accordingly. */
  open fun rebindBinders(
      context: MountContext,
      binderIds: ScatterSet<BinderId>,
      content: MOUNT_CONTENT,
      layoutData: Any?,
      bindData: BindData,
  ) {
    binderIds.forEach { binderId ->
      val holder =
          when (binderId.type) {
            BinderType.MOUNT ->
                when (val key = binderId.key) {
                  is IndexedBinderKey -> fixedMountBinders?.get(key.index)
                  else -> optionalMountBinderKeyToDelegateMap?.get(key)
                }
            BinderType.ATTACH -> attachBinderKeyToDelegateMap?.get(binderId.key)
          }

      if (holder != null) {
        // This path skips shouldUpdate, so this is the only chance to record the rebind.
        // Must stay above the bind: onBindComplete only fills in an entry that already exists,
        // so reporting after the bind silently drops every bind duration.
        // Not gated on collectBindReasons: the callback carries no values.
        context.binderObserver?.onStateReadRebind(binderId)
        try {
          // 1. Unbind the binder.
          val currentBindData =
              when (binderId.type) {
                BinderType.MOUNT ->
                    when (val key = binderId.key) {
                      is IndexedBinderKey -> bindData.removeFixedBinderBindData(key.index)
                      else -> bindData.removeOptionalMountBindersBindData(key)
                    }
                BinderType.ATTACH -> bindData.removeAttachBindersBindData(binderId.key)
              }
          holder.unbind(context, content, layoutData, currentBindData)

          // 2. Rebind the binder.
          val newBindData = holder.bind(context, content, layoutData)
          when (binderId.type) {
            BinderType.MOUNT ->
                when (val key = binderId.key) {
                  is IndexedBinderKey ->
                      bindData.setFixedBindersBindData(
                          newBindData,
                          key.index,
                          fixedMountBinders?.size ?: 0,
                      )
                  else ->
                      bindData.setOptionalMountBindersBindData(
                          newBindData,
                          key,
                          optionalMountBinders?.size ?: 0,
                      )
                }
            BinderType.ATTACH ->
                bindData.setAttachBindersBindData(
                    newBindData,
                    binderId.key,
                    attachBinders?.size ?: 0,
                )
          }
        } catch (exception: Exception) {
          throw RenderUnitOperationException(
              renderUnit = this,
              message = "Exception rebinding binder: ${holder.binder.description}",
              cause = exception,
          )
        }
      } else {
        ErrorReporter.report(
            LogLevel.DEBUG,
            "RenderUnit.rebindBinders",
            "Binder with id=$binderId not found",
        )
      }
    }
  }

  /**
   * Unbind and rebind all binders which should update compared to a previous (i.e. current)
   * RenderUnit.
   */
  open fun updateBinders(
      context: MountContext,
      content: MOUNT_CONTENT,
      currentRenderUnit: RenderUnit<MOUNT_CONTENT>,
      currentLayoutData: Any?,
      newLayoutData: Any?,
      mountDelegate: MountDelegate?,
      bindData: BindData,
      isAttached: Boolean,
      extraBindersToUpdate: ScatterSet<BinderId> = emptyScatterSet(),
  ) {
    // Use the allocation-free updateBindersBitmask when every binder list is small enough to fit
    // into its fixed-width bitmasks (at most MAX_DYNAMIC_BINDERS_FOR_MASK entries each); otherwise
    // use updateBindersWithLists, which handles any size but allocates intermediate ArrayLists.
    val canUseBitmask =
        sizeOrZero(attachBinders) <= MAX_DYNAMIC_BINDERS_FOR_MASK &&
            sizeOrZero(currentRenderUnit.attachBinders) <= MAX_DYNAMIC_BINDERS_FOR_MASK &&
            sizeOrZero(optionalMountBinders) <= MAX_DYNAMIC_BINDERS_FOR_MASK &&
            sizeOrZero(currentRenderUnit.optionalMountBinders) <= MAX_DYNAMIC_BINDERS_FOR_MASK
    if (canUseBitmask) {
      updateBindersBitmask(
          context,
          content,
          currentRenderUnit,
          currentLayoutData,
          newLayoutData,
          mountDelegate,
          bindData,
          isAttached,
          extraBindersToUpdate,
      )
    } else {
      updateBindersWithLists(
          context,
          content,
          currentRenderUnit,
          currentLayoutData,
          newLayoutData,
          mountDelegate,
          bindData,
          isAttached,
          extraBindersToUpdate,
      )
    }
  }

  /**
   * List-based fallback for [updateBinders], used when a binder list exceeds
   * [MAX_DYNAMIC_BINDERS_FOR_MASK] and so cannot be resolved with the packed bitmasks of
   * [updateBindersBitmask]. Collects the binders to bind and unbind into intermediate ArrayLists.
   */
  private fun updateBindersWithLists(
      context: MountContext,
      content: MOUNT_CONTENT,
      currentRenderUnit: RenderUnit<MOUNT_CONTENT>,
      currentLayoutData: Any?,
      newLayoutData: Any?,
      mountDelegate: MountDelegate?,
      bindData: BindData,
      isAttached: Boolean,
      extraBindersToUpdate: ScatterSet<BinderId>,
  ) {
    val tracer = context.tracer
    val isTracing = tracer.isTracing()
    val attachBindersForBind: MutableList<BinderHolder> = ArrayList(sizeOrZero(attachBinders))
    val attachBindersForUnbind: MutableList<BinderHolder> =
        ArrayList(sizeOrZero(currentRenderUnit.attachBinders))
    val optionalMountBindersForBind: MutableList<BinderHolder> =
        ArrayList(sizeOrZero(optionalMountBinders))
    val optionalMountBindersForUnbind: MutableList<BinderHolder> =
        ArrayList(sizeOrZero(currentRenderUnit.optionalMountBinders))

    // 1. Resolve fixed mount binders which should update.
    val (fixedMountBindersToUpdate, fixedBindersToRestart) =
        try {
          resolveFixedMountBindersToUpdate(
              context,
              currentRenderUnit.fixedMountBinders,
              fixedMountBinders,
              currentLayoutData,
              newLayoutData,
              extraBindersToUpdate,
          )
        } catch (exception: Exception) {
          throw RenderUnitOperationException(
              renderUnit = this,
              message = "Exception resolving fixed mount binders to update",
              cause = exception,
          )
        }

    // 2. Diff the binders to resolve what's to bind/unbind.
    resolveBindersToUpdate(
        context,
        currentRenderUnit.attachBinders,
        attachBinders,
        currentRenderUnit.attachBinderKeyToDelegateMap,
        currentLayoutData,
        newLayoutData,
        attachBindersForBind,
        attachBindersForUnbind,
        extraBindersToUpdate,
    )
    resolveBindersToUpdate(
        context,
        currentRenderUnit.optionalMountBinders,
        optionalMountBinders,
        currentRenderUnit.optionalMountBinderKeyToDelegateMap,
        currentLayoutData,
        newLayoutData,
        optionalMountBindersForBind,
        optionalMountBindersForUnbind,
        extraBindersToUpdate,
    )
    val extensionStatesToUpdate: List<ExtensionState<*>>? =
        mountDelegate?.collateExtensionsToUpdate(
            currentRenderUnit,
            currentLayoutData,
            this,
            newLayoutData,
            tracer,
        )

    // 3. Unbind all attach binders which should update (only if currently attached).
    if (isAttached) {
      if (mountDelegate != null && extensionStatesToUpdate != null) {
        MountDelegate.onUnbindItemWhichRequiresUpdate(
            extensionStatesToUpdate,
            currentRenderUnit,
            currentLayoutData,
            this,
            newLayoutData,
            content,
            tracer,
        )
      }
      if (isTracing) {
        tracer.beginSection(sectionName("$description:detach"))
      }
      for (i in attachBindersForUnbind.indices.reversed()) {
        val holder = attachBindersForUnbind[i]
        if (isTracing) {
          tracer.beginSection(sectionName(holder.binder.description))
        }
        holder.unbind(
            context,
            content,
            currentLayoutData,
            bindData.removeAttachBindersBindData(holder.binderKey),
        )
        if (isTracing) {
          tracer.endSection()
        }
      }
      if (isTracing) {
        tracer.endSection()
      }
    }

    // 4. Unbind all optional and fixed mount binders which should update.
    if (mountDelegate != null && extensionStatesToUpdate != null) {
      MountDelegate.onUnmountItemWhichRequiresUpdate(
          extensionStatesToUpdate,
          currentRenderUnit,
          currentLayoutData,
          this,
          newLayoutData,
          content,
          tracer,
      )
    }
    if (isTracing) {
      tracer.beginSection(sectionName("$description:unmount-optional"))
    }
    for (i in optionalMountBindersForUnbind.indices.reversed()) {
      val holder = optionalMountBindersForUnbind[i]
      if (isTracing) {
        tracer.beginSection(sectionName(holder.binder.description))
      }
      holder.unbind(
          context,
          content,
          currentLayoutData,
          bindData.removeOptionalMountBindersBindData(holder.binderKey),
      )
      if (isTracing) {
        tracer.endSection()
      }
    }
    if (isTracing) {
      tracer.endSection()
    }
    if (fixedMountBindersToUpdate != 0L) {
      if (isTracing) {
        tracer.beginSection(sectionName("$description:unmount-fixed"))
      }
      fixedMountBinders?.let { mountBinders ->
        for (i in mountBinders.indices.reversed()) {
          if (fixedMountBindersToUpdate and (0x1L shl i) != 0L) {
            val holder = currentRenderUnit.fixedMountBinders?.get(i) ?: continue
            if (isTracing) {
              tracer.beginSection(sectionName(holder.binder.description))
            }
            holder.unbind(
                context,
                content,
                currentLayoutData,
                bindData.removeFixedBinderBindData(i),
            )
            if (isTracing) {
              tracer.endSection()
            }
          }
        }
      }
      if (isTracing) {
        tracer.endSection()
      }
    }

    // 5. Rebind all fixed and optional mount binders which did update.
    if (fixedMountBindersToUpdate != 0L) {
      val fixedMountBindersSize = fixedMountBinders?.size ?: 0
      if (isTracing) {
        tracer.beginSection(sectionName("$description:mount-fixed"))
      }
      for (i in 0 until fixedMountBindersSize) {
        val shouldUpdate = fixedMountBindersToUpdate and (0x1L shl i) != 0L
        val restartContinuations = fixedBindersToRestart and (0x1L shl i) != 0L
        if (shouldUpdate || restartContinuations) {
          val holder = fixedMountBinders?.get(i) ?: continue
          if (isTracing) {
            tracer.beginSection(sectionName(holder.binder.description))
          }
          if (restartContinuations) {
            holder.restartContinuations(context.continuationContext)
          }
          val binderBindData = holder.bind(context, content, newLayoutData)
          bindData.setFixedBindersBindData(binderBindData, i, fixedMountBindersSize)
          if (isTracing) {
            tracer.endSection()
          }
        }
      }
      if (isTracing) {
        tracer.endSection()
      }
    }
    val optionalMountBindersSize = optionalMountBinders?.size ?: 0
    if (isTracing) {
      tracer.beginSection(sectionName("$description:mount-optional"))
    }
    for (i in optionalMountBindersForBind.indices) {
      val holder = optionalMountBindersForBind[i]
      if (isTracing) {
        tracer.beginSection(sectionName(holder.binder.description))
      }
      if (holder.hasContinuations) {
        holder.restartContinuations(context.continuationContext)
      } else {
        val binderBindData = holder.bind(context, content, newLayoutData)
        bindData.setOptionalMountBindersBindData(
            binderBindData,
            holder.binderKey,
            optionalMountBindersSize,
        )
      }
      if (isTracing) {
        tracer.endSection()
      }
    }
    if (isTracing) {
      tracer.endSection()
    }
    if (mountDelegate != null && extensionStatesToUpdate != null) {
      MountDelegate.onMountItemWhichRequiresUpdate(
          extensionStatesToUpdate,
          currentRenderUnit,
          currentLayoutData,
          this,
          newLayoutData,
          content,
          tracer,
      )
    }

    // 6. Rebind all attach binders which did update.
    val attachBindersSize = attachBinders?.size ?: 0
    if (isTracing) {
      tracer.beginSection(sectionName("$description:attach"))
    }
    for (i in attachBindersForBind.indices) {
      val holder = attachBindersForBind[i]
      if (isTracing) {
        tracer.beginSection(sectionName(holder.binder.description))
      }
      if (holder.hasContinuations) {
        holder.restartContinuations(context.continuationContext)
      } else {
        val binderBindData = holder.bind(context, content, newLayoutData)
        bindData.setAttachBindersBindData(binderBindData, holder.binderKey, attachBindersSize)
      }
      if (isTracing) {
        tracer.endSection()
      }
    }
    if (isTracing) {
      tracer.endSection()
    }
    if (mountDelegate != null && extensionStatesToUpdate != null) {
      MountDelegate.onBindItemWhichRequiresUpdate(
          extensionStatesToUpdate,
          currentRenderUnit,
          currentLayoutData,
          this,
          newLayoutData,
          content,
          tracer,
      )
    }
  }

  /**
   * Allocation-free counterpart to [updateBindersWithLists]: resolves which binders to bind and
   * unbind as packed Long bitmasks rather than intermediate ArrayLists. Valid only when every
   * binder list has at most [MAX_DYNAMIC_BINDERS_FOR_MASK] entries (gated by [updateBinders]).
   */
  private fun updateBindersBitmask(
      context: MountContext,
      content: MOUNT_CONTENT,
      currentRenderUnit: RenderUnit<MOUNT_CONTENT>,
      currentLayoutData: Any?,
      newLayoutData: Any?,
      mountDelegate: MountDelegate?,
      bindData: BindData,
      isAttached: Boolean,
      extraBindersToUpdate: ScatterSet<BinderId>,
  ) {
    val tracer = context.tracer
    val isTracing = tracer.isTracing()

    // 1. Resolve fixed mount binders which should update.
    val (fixedMountBindersToUpdate, fixedBindersToRestart) =
        try {
          resolveFixedMountBindersToUpdate(
              context,
              currentRenderUnit.fixedMountBinders,
              fixedMountBinders,
              currentLayoutData,
              newLayoutData,
              extraBindersToUpdate,
          )
        } catch (exception: Exception) {
          throw RenderUnitOperationException(
              renderUnit = this,
              message = "Exception resolving fixed mount binders to update",
              cause = exception,
          )
        }

    // 2. Diff the binders to resolve what's to bind/unbind using packed bitmasks.
    val attachPackedMasks = resolveBindersToUpdateMasks(
        context,
        currentRenderUnit.attachBinders,
        attachBinders,
        currentRenderUnit.attachBinderKeyToDelegateMap,
        currentLayoutData,
        newLayoutData,
        extraBindersToUpdate,
    )
    val attachBindersToBindMask = attachPackedMasks and 0xFFFFFFFFL
    val attachBindersToUnbindMask = attachPackedMasks ushr 32
    val optionalMountPackedMasks = resolveBindersToUpdateMasks(
        context,
        currentRenderUnit.optionalMountBinders,
        optionalMountBinders,
        currentRenderUnit.optionalMountBinderKeyToDelegateMap,
        currentLayoutData,
        newLayoutData,
        extraBindersToUpdate,
    )
    val optionalMountBindersToBindMask = optionalMountPackedMasks and 0xFFFFFFFFL
    val optionalMountBindersToUnbindMask = optionalMountPackedMasks ushr 32
    val extensionStatesToUpdate: List<ExtensionState<*>>? =
        mountDelegate?.collateExtensionsToUpdate(
            currentRenderUnit,
            currentLayoutData,
            this,
            newLayoutData,
            tracer,
        )

    // 3. Unbind all attach binders which should update (only if currently attached).
    if (isAttached) {
      if (mountDelegate != null && extensionStatesToUpdate != null) {
        MountDelegate.onUnbindItemWhichRequiresUpdate(
            extensionStatesToUpdate,
            currentRenderUnit,
            currentLayoutData,
            this,
            newLayoutData,
            content,
            tracer,
        )
      }
      if (isTracing) {
        tracer.beginSection(sectionName("$description:detach"))
      }
      currentRenderUnit.attachBinders?.let { currentAttachBinders ->
        for (i in currentAttachBinders.indices.reversed()) {
          if (attachBindersToUnbindMask and (1L shl i) != 0L) {
            val holder = currentAttachBinders[i]
            if (isTracing) {
              tracer.beginSection(sectionName(holder.binder.description))
            }
            holder.unbind(
                context,
                content,
                currentLayoutData,
                bindData.removeAttachBindersBindData(holder.binderKey),
            )
            if (isTracing) {
              tracer.endSection()
            }
          }
        }
      }
      if (isTracing) {
        tracer.endSection()
      }
    }

    // 4. Unbind all optional and fixed mount binders which should update.
    if (mountDelegate != null && extensionStatesToUpdate != null) {
      MountDelegate.onUnmountItemWhichRequiresUpdate(
          extensionStatesToUpdate,
          currentRenderUnit,
          currentLayoutData,
          this,
          newLayoutData,
          content,
          tracer,
      )
    }
    if (isTracing) {
      tracer.beginSection(sectionName("$description:unmount-optional"))
    }
    currentRenderUnit.optionalMountBinders?.let { currentOptionalMountBinders ->
      for (i in currentOptionalMountBinders.indices.reversed()) {
        if (optionalMountBindersToUnbindMask and (1L shl i) != 0L) {
          val holder = currentOptionalMountBinders[i]
          if (isTracing) {
            tracer.beginSection(sectionName(holder.binder.description))
          }
          holder.unbind(
              context,
              content,
              currentLayoutData,
              bindData.removeOptionalMountBindersBindData(holder.binderKey),
          )
          if (isTracing) {
            tracer.endSection()
          }
        }
      }
    }
    if (isTracing) {
      tracer.endSection()
    }
    if (fixedMountBindersToUpdate != 0L) {
      if (isTracing) {
        tracer.beginSection(sectionName("$description:unmount-fixed"))
      }
      fixedMountBinders?.let { mountBinders ->
        for (i in mountBinders.indices.reversed()) {
          if (fixedMountBindersToUpdate and (0x1L shl i) != 0L) {
            val holder = currentRenderUnit.fixedMountBinders?.get(i) ?: continue
            if (isTracing) {
              tracer.beginSection(sectionName(holder.binder.description))
            }
            holder.unbind(
                context,
                content,
                currentLayoutData,
                bindData.removeFixedBinderBindData(i),
            )
            if (isTracing) {
              tracer.endSection()
            }
          }
        }
      }
      if (isTracing) {
        tracer.endSection()
      }
    }

    // 5. Rebind all fixed and optional mount binders which did update.
    if (fixedMountBindersToUpdate != 0L) {
      val fixedMountBindersSize = fixedMountBinders?.size ?: 0
      if (isTracing) {
        tracer.beginSection(sectionName("$description:mount-fixed"))
      }
      for (i in 0 until fixedMountBindersSize) {
        val shouldUpdate = fixedMountBindersToUpdate and (0x1L shl i) != 0L
        val restartContinuations = fixedBindersToRestart and (0x1L shl i) != 0L
        if (shouldUpdate || restartContinuations) {
          val holder = fixedMountBinders?.get(i) ?: continue
          if (isTracing) {
            tracer.beginSection(sectionName(holder.binder.description))
          }
          if (restartContinuations) {
            holder.restartContinuations(context.continuationContext)
          }
          val binderBindData = holder.bind(context, content, newLayoutData)
          bindData.setFixedBindersBindData(binderBindData, i, fixedMountBindersSize)
          if (isTracing) {
            tracer.endSection()
          }
        }
      }
      if (isTracing) {
        tracer.endSection()
      }
    }
    val optionalMountBindersSize = optionalMountBinders?.size ?: 0
    if (isTracing) {
      tracer.beginSection(sectionName("$description:mount-optional"))
    }
    optionalMountBinders?.let { newOptionalMountBinders ->
      for (i in newOptionalMountBinders.indices) {
        if (optionalMountBindersToBindMask and (1L shl i) != 0L) {
          val holder = newOptionalMountBinders[i]
          if (isTracing) {
            tracer.beginSection(sectionName(holder.binder.description))
          }
          if (holder.hasContinuations) {
            holder.restartContinuations(context.continuationContext)
          } else {
            val binderBindData = holder.bind(context, content, newLayoutData)
            bindData.setOptionalMountBindersBindData(
                binderBindData,
                holder.binderKey,
                optionalMountBindersSize,
            )
          }
          if (isTracing) {
            tracer.endSection()
          }
        }
      }
    }
    if (isTracing) {
      tracer.endSection()
    }
    if (mountDelegate != null && extensionStatesToUpdate != null) {
      MountDelegate.onMountItemWhichRequiresUpdate(
          extensionStatesToUpdate,
          currentRenderUnit,
          currentLayoutData,
          this,
          newLayoutData,
          content,
          tracer,
      )
    }

    // 6. Rebind all attach binders which did update.
    val attachBindersSize = attachBinders?.size ?: 0
    if (isTracing) {
      tracer.beginSection(sectionName("$description:attach"))
    }
    attachBinders?.let { newAttachBinders ->
      for (i in newAttachBinders.indices) {
        if (attachBindersToBindMask and (1L shl i) != 0L) {
          val holder = newAttachBinders[i]
          if (isTracing) {
            tracer.beginSection(sectionName(holder.binder.description))
          }
          if (holder.hasContinuations) {
            holder.restartContinuations(context.continuationContext)
          } else {
            val binderBindData = holder.bind(context, content, newLayoutData)
            bindData.setAttachBindersBindData(binderBindData, holder.binderKey, attachBindersSize)
          }
          if (isTracing) {
            tracer.endSection()
          }
        }
      }
    }
    if (isTracing) {
      tracer.endSection()
    }
    if (mountDelegate != null && extensionStatesToUpdate != null) {
      MountDelegate.onBindItemWhichRequiresUpdate(
          extensionStatesToUpdate,
          currentRenderUnit,
          currentLayoutData,
          this,
          newLayoutData,
          content,
          tracer,
      )
    }
  }

  open fun <T : Binder<*, *, *>?> findAttachBinderByKey(key: BinderKey): T? {
    val holder = attachBinderKeyToDelegateMap?.get(key)
    return holder?.binder as T?
  }

  open fun containsAttachBinder(delegateBinder: DelegateBinder<*, *, *>): Boolean {
    return attachBinderKeyToDelegateMap?.containsKey(delegateBinder.binder.key) ?: false
  }

  open fun containsOptionalMountBinder(delegateBinder: DelegateBinder<*, *, *>): Boolean {
    return optionalMountBinderKeyToDelegateMap?.containsKey(delegateBinder.binder.key) ?: false
  }

  /**
   * A binder is a pair of data Model and [Binder]. The binder will bind the model to a matching
   * content type defined.
   */
  class DelegateBinder<MODEL, CONTENT, BIND_DATA : Any>
  private constructor(
      internal val model: MODEL,
      val binder: Binder<MODEL, CONTENT, BIND_DATA>,
  ) {

    companion object {
      /**
       * Create a binder with a Model and [Binder] which will bind the given Model to the content
       * type which will be provided by the RenderUnit.
       */
      @JvmStatic
      fun <MODEL, CONTENT, BIND_DATA : Any> createDelegateBinder(
          model: MODEL,
          binder: Binder<MODEL, CONTENT, BIND_DATA>,
      ): DelegateBinder<MODEL, CONTENT, BIND_DATA> {
        return DelegateBinder(model, binder)
      }
    }
  }

  /**
   * Represents a single bind function. Every bind has an equivalent unbind and a shouldUpdate
   * callback
   */
  interface Binder<MODEL, CONTENT, BIND_DATA : Any> {

    /**
     * Decides if the model should be re-bound to the content. If this method returns true, then
     * unbind will be called followed by bind.
     */
    fun shouldUpdate(
        currentModel: MODEL,
        newModel: MODEL,
        currentLayoutData: Any?,
        nextLayoutData: Any?,
    ): Boolean

    fun BinderScope.bind(
        context: Context,
        content: CONTENT,
        model: MODEL,
        layoutData: Any?,
    ): BIND_DATA? {
      return this@Binder.bind(context, content, model, layoutData)
    }

    /**
     * Binds the model to the content and returns optional bind data that will be passed to unbind.
     */
    fun bind(context: Context, content: CONTENT, model: MODEL, layoutData: Any?): BIND_DATA? {
      return null
    }

    fun BinderScope.unbind(
        context: Context,
        content: CONTENT,
        model: MODEL,
        layoutData: Any?,
        bindData: BIND_DATA?,
    ) {
      return this@Binder.unbind(context, content, model, layoutData, bindData)
    }

    /** Unbinds the model from the content. */
    fun unbind(
        context: Context,
        content: CONTENT,
        model: MODEL,
        layoutData: Any?,
        bindData: BIND_DATA?,
    ): Unit = Unit

    val description: String
      get() = getSectionNameForTracing(javaClass)

    val key: BinderKey
      get() = ClassBinderKey.of(javaClass)
  }

  companion object {
    // RenderUnit's description is used for tracing, and according to:
    // https://developer.android.com/reference/android/os/Trace#beginSection(java.lang.String)
    // the max length of the tracing section name is 127
    const val MAX_DESCRIPTION_LENGTH: Int = 127
    private const val MAX_FIXED_MOUNT_BINDERS_COUNT = 64
    // updateBindersBitmask packs a bind mask and an unbind mask into the low and high halves of a
    // single 64-bit Long, so each binder list may hold at most 32 entries to use that path.
    private const val MAX_DYNAMIC_BINDERS_FOR_MASK = 32
    private const val EMPTY_PACKED_MASKS = 0L
    private val EMPTY_FIXED_BINDERS: Pair<Long, Long> = Pair(0, 0)

    private fun <MOUNT_CONTENT : Any> createFixedBinders(
        renderUnit: RenderUnit<MOUNT_CONTENT>,
        delegates: List<DelegateBinder<*, in MOUNT_CONTENT, *>>?,
    ): List<BinderHolder>? {
      if (delegates.isNullOrEmpty()) {
        return null
      }
      return delegates.mapIndexed { index, delegate ->
        val binderId = BinderId(renderUnit.id, BinderType.MOUNT, IndexedBinderKey(index))
        if (RenderCoreConfig.isDebugModeEnabled) {
          binderId.renderUnitDebugDescription = renderUnit.description
          binderId.binderDebugDescription = delegate.binder.description
        }
        BinderHolder(
            renderUnit.continuationInfo,
            binderId,
            delegate.binder as Binder<Any?, Any, Any>,
            delegate.model,
        )
      }
    }

    // Make sure a binder with the same Binder is not already defined in this RenderUnit.
    // If that's the case, remove the old binder and add the new one at the current list position
    // which is at the end.
    private fun <MOUNT_CONTENT : Any> addBinder(
        binderKeyToBinderMap: MutableScatterMap<BinderKey, BinderHolder>,
        binders: MutableList<BinderHolder>,
        delegate: DelegateBinder<*, in MOUNT_CONTENT, *>,
        renderUnit: RenderUnit<MOUNT_CONTENT>,
        type: BinderType,
    ) {
      val binderId = BinderId(renderUnit.id, type, key = delegate.binder.key)
      if (RenderCoreConfig.isDebugModeEnabled) {
        binderId.renderUnitDebugDescription = renderUnit.description
        binderId.binderDebugDescription = delegate.binder.description
      }
      val binderHolder = BinderHolder(
          renderUnit.continuationInfo,
          binderId,
          delegate.binder as Binder<Any?, Any, Any>,
          delegate.model,
      )
      val prevBinder = binderKeyToBinderMap.put(binderId.key, binderHolder)
      if (prevBinder != null) {
        // A binder with the same type was already present and it should be removed.
        var found = false
        for (i in binders.indices.reversed()) {
          if (binders[i].binderKey == binderId.key) {
            binders.removeAt(i)
            found = true
            break
          }
        }
        check(found) { "Binder Map and Binder List out of sync!" }
      }
      binders.add(binderHolder)
    }

    /**
     * This methods validates current and new fixed mount binders, calling shouldUpdate if needed,
     * and returning a long value with bits set to 1 for all fixed binders that need to be updated.
     */
    private fun resolveFixedMountBindersToUpdate(
        context: MountContext,
        currentFixedBinders: List<BinderHolder>?,
        newFixedBinders: List<BinderHolder>?,
        currentLayoutData: Any?,
        newLayoutData: Any?,
        extraBindersToUpdate: ScatterSet<BinderId>,
    ): Pair<Long, Long> {
      if (currentFixedBinders.isNullOrEmpty() && newFixedBinders.isNullOrEmpty()) {
        return EMPTY_FIXED_BINDERS
      }
      var fixedMountBindersToUpdate: Long = 0
      var fixedBindersToRestart: Long = 0
      check(currentFixedBinders?.size == newFixedBinders?.size) {
        ("Current and new fixed Mount Binders are of sync: \n" +
            "currentFixedBinders.size() = " +
            currentFixedBinders?.size +
            "\n" +
            "newFixedBinders.size() = " +
            newFixedBinders?.size)
      }
      currentFixedBinders ?: return EMPTY_FIXED_BINDERS
      newFixedBinders ?: return EMPTY_FIXED_BINDERS
      for (i in currentFixedBinders.indices) {
        val currentHolder = currentFixedBinders[i]
        val newHolder = newFixedBinders[i]
        val isStateReadRebind = newHolder.binderId in extraBindersToUpdate
        if (isStateReadRebind) {
          // This path skips shouldUpdate by design, so it is the only chance to record the rebind.
          // The tracer creates entries nowhere else, and the bind duration attaches to this one.
          // Not gated on collectBindReasons, as the callback carries no values.
          context.binderObserver?.onStateReadRebind(newHolder.binderId)
        }
        if (
            isStateReadRebind ||
                newHolder.shouldUpdate(context, currentHolder, currentLayoutData, newLayoutData)
        ) {
          fixedMountBindersToUpdate = fixedMountBindersToUpdate or (0x1L shl i)
        } else if (currentHolder.hasContinuations) {
          fixedBindersToRestart = fixedBindersToRestart or (0x1L shl i)
          currentHolder.transferContinuations(newHolder)
        }
      }
      return Pair(fixedMountBindersToUpdate, fixedBindersToRestart)
    }

    /**
     * Diffs current and new binders, calling shouldUpdate if needed, and returning a list of
     * binders from the "current" ones to unbind, and a list of binders from the "new" ones to bind.
     */
    private fun resolveBindersToUpdate(
        context: MountContext,
        currentBinders: List<BinderHolder>?,
        newBinders: List<BinderHolder>?,
        currentBinderTypeToBinderMap: ScatterMap<BinderKey, BinderHolder>?,
        currentLayoutData: Any?,
        newLayoutData: Any?,
        bindersToBind: MutableList<BinderHolder>,
        bindersToUnbind: MutableList<BinderHolder>,
        extraBindersToUpdate: ScatterSet<BinderId>,
    ) {

      // There's nothing to unbind because there aren't any current binders, we need to bind all
      // new binders.
      if (currentBinders.isNullOrEmpty()) {
        newBinders?.let { bindersToBind.addAll(it) }
        return
      }

      // There's no new binders. All current binders have to be unbound.
      if (newBinders.isNullOrEmpty()) {
        bindersToUnbind.addAll(currentBinders)
        return
      }
      val binderToShouldUpdate = MutableScatterMap<BinderKey, Boolean>(newBinders.size)

      // Parse all new binders and resolve which ones are to bind.
      for (i in newBinders.indices) {
        val newHolder = newBinders[i]
        val binderKey = newHolder.binderKey
        val currentHolder = currentBinderTypeToBinderMap?.get(binderKey)
        if (currentHolder == null) {
          // Found new binder, has to be bound.
          bindersToBind.add(newHolder)
          continue
        }
        val isStateReadRebind = newHolder.binderId in extraBindersToUpdate
        if (isStateReadRebind) {
          // This path skips shouldUpdate by design, so it is the only chance to record the rebind.
          // The tracer creates entries nowhere else, and the bind duration attaches to this one.
          // Not gated on collectBindReasons, as the callback carries no values.
          context.binderObserver?.onStateReadRebind(newHolder.binderId)
        }
        val shouldUpdate =
            isStateReadRebind ||
                newHolder.shouldUpdate(context, currentHolder, currentLayoutData, newLayoutData)
        // Memoize the result for the next for-loop.
        binderToShouldUpdate[binderKey] = shouldUpdate
        if (!shouldUpdate) {
          currentHolder.transferContinuations(newHolder)
        }

        if (shouldUpdate || currentHolder.hasContinuations) {
          bindersToBind.add(newHolder)
        }
      }

      // Parse all current binders and resolve which ones are to unbind.
      for (i in currentBinders.indices) {
        val currentHolder = currentBinders[i]
        val binderKey = currentHolder.binderKey
        if (
            !binderToShouldUpdate.containsKey(binderKey) || binderToShouldUpdate[binderKey] == true
        ) {
          // Found a current binder which either is not in the new RenderUnit or shouldUpdate is
          // true, therefore we need to unbind it.
          bindersToUnbind.add(currentHolder)
        }
      }
    }

    /**
     * Diffs current and new binders, calling shouldUpdate if needed, and returning a packed Long:
     * low 32 bits = toBindMask (indices in [newBinders]), high 32 bits = toUnbindMask (indices in
     * [currentBinders]). Zero allocations.
     */
    private fun resolveBindersToUpdateMasks(
        context: MountContext,
        currentBinders: List<BinderHolder>?,
        newBinders: List<BinderHolder>?,
        currentBinderTypeToBinderMap: ScatterMap<BinderKey, BinderHolder>?,
        currentLayoutData: Any?,
        newLayoutData: Any?,
        extraBindersToUpdate: ScatterSet<BinderId>,
    ): Long {

      if (currentBinders.isNullOrEmpty()) {
        if (newBinders.isNullOrEmpty()) return EMPTY_PACKED_MASKS
        return allBitsMask32(newBinders.size)
      }

      if (newBinders.isNullOrEmpty()) {
        return allBitsMask32(currentBinders.size) shl 32
      }

      var toBindMask = 0L
      var toUnbindMask = 0L
      val binderToShouldUpdate = MutableScatterMap<BinderKey, Boolean>(newBinders.size)

      for (i in newBinders.indices) {
        val newHolder = newBinders[i]
        val binderKey = newHolder.binderKey
        val currentHolder = currentBinderTypeToBinderMap?.get(binderKey)
        if (currentHolder == null) {
          toBindMask = toBindMask or (1L shl i)
          continue
        }
        val isStateReadRebind = newHolder.binderId in extraBindersToUpdate
        if (isStateReadRebind) {
          // This path skips shouldUpdate by design, so it is the only chance to record the rebind.
          // The tracer creates entries nowhere else, and the bind duration attaches to this one.
          // Not gated on collectBindReasons, as the callback carries no values.
          context.binderObserver?.onStateReadRebind(newHolder.binderId)
        }
        val shouldUpdate =
            isStateReadRebind ||
                newHolder.shouldUpdate(context, currentHolder, currentLayoutData, newLayoutData)
        binderToShouldUpdate[binderKey] = shouldUpdate
        if (!shouldUpdate) {
          currentHolder.transferContinuations(newHolder)
        }
        if (shouldUpdate || currentHolder.hasContinuations) {
          toBindMask = toBindMask or (1L shl i)
        }
      }

      for (i in currentBinders.indices) {
        val currentHolder = currentBinders[i]
        val binderKey = currentHolder.binderKey
        if (
            !binderToShouldUpdate.containsKey(binderKey) || binderToShouldUpdate[binderKey] == true
        ) {
          toUnbindMask = toUnbindMask or (1L shl i)
        }
      }

      return toBindMask or (toUnbindMask shl 32)
    }

    private fun allBitsMask32(size: Int): Long = if (size >= 32) 0xFFFFFFFFL else (1L shl size) - 1L

    private fun sizeOrZero(collection: Collection<*>?): Int {
      return collection?.size ?: 0
    }

    private fun sectionName(name: String): String {
      return if (name.length <= MAX_DESCRIPTION_LENGTH) {
        name
      } else name.substring(0, MAX_DESCRIPTION_LENGTH)
    }
  }

  /**
   * This is a wrapper [Exception] that appends information about the [RenderUnit] that caused the
   * exception.
   *
   * The [message] should help to reflect which was the faulty operation and provide specific
   * contextual data if possible.
   */
  class RenderUnitOperationException(renderUnit: RenderUnit<*>, message: String, cause: Throwable) :
      RuntimeException("[${renderUnit.description}] $message") {

    init {
      initCause(cause)
      stackTrace = emptyArray()
    }
  }
}

private class BinderHolder(
    val continuationInfo: ContinuationInfo,
    override val binderId: BinderId,
    val binder: RenderUnit.Binder<Any?, Any, Any>,
    private val model: Any?,
) : BinderScope, ContinuationValueRecorder {
  override val binderModel: Any? = model
  inline val binderKey: BinderKey
    get() = binderId.key

  val hasContinuations: Boolean
    get() = !continuations.isNullOrEmpty()

  private var continuations: MutableList<MountContinuation<*>>? = null

  /**
   * Stashed by [bind]/[unbind] so [useContinuation] can run a freshly-registered continuation
   * against the per-[MountState] context. Outside of a bind/unbind call (which includes any
   * subsequent [restartContinuations] call) it is `null` and lookups fall back to the global
   * [continuationContext].
   */
  private var currentContinuationContext: MountContinuationContext? = null

  /**
   * Continuation value versions this binder's continuations read on their last successful run,
   * keyed by continuation value key. Used to detect when the current reader reports a newer value
   * the continuation must re-run against. `null` until a continuation reads a value.
   */
  private var accessedVersions: MutableScatterMap<Any, Long>? = null

  override fun record(key: Any, version: Long) {
    val values = accessedVersions ?: MutableScatterMap<Any, Long>(2).also { accessedVersions = it }
    values[key] = version
  }

  private fun beginContinuationVersionRecording() {
    accessedVersions?.clear()
  }

  private fun finishContinuationVersionRecording(success: Boolean) {
    if (!success) {
      accessedVersions = null
    }
  }

  /**
   * Whether the current reader reports a continuation value version newer than what this binder's
   * continuations last accessed — i.e. a restart would actually do work. A binder whose
   * continuations read no versioned values is treated as always-dirty, since we can't reason about
   * its freshness.
   */
  fun hasNewContinuationValues(context: MountContinuationContext): Boolean {
    if (!hasContinuations) {
      return false
    }
    val accessed = accessedVersions
    if (accessed == null || accessed.isEmpty()) {
      return true
    }
    accessed.forEach { key, accessedVersion ->
      val currentVersion = context.peekVersion(key)
      if (
          accessedVersion == UNKNOWN_CONTINUATION_VALUE_VERSION ||
              currentVersion == UNKNOWN_CONTINUATION_VALUE_VERSION ||
              currentVersion != accessedVersion
      ) {
        return true
      }
    }
    return false
  }

  @Suppress("UNCHECKED_CAST")
  fun shouldUpdate(
      context: MountContext,
      previous: BinderHolder,
      currentLayoutData: Any?,
      nextLayoutData: Any?,
  ): Boolean {
    val observer =
        context.binderObserver
            ?: return binder.shouldUpdate(previous.model, model, currentLayoutData, nextLayoutData)

    val shouldUpdate =
        observer.observeShouldUpdate(binderId) {
          binder.shouldUpdate(previous.model, model, currentLayoutData, nextLayoutData)
        }

    // Both models are only live here, so this is the one place a rebind can be attributed. Tell the
    // observer either way: silence would be indistinguishable from a binder with no dep model.
    if (shouldUpdate && binder is DepsModel) {
      if (RenderCoreConfig.collectBindReasons) {
        observer.onDepsChanged(binderId, describeDepChanges(previous.model, model))
      } else {
        observer.onDepsNotCollected(binderId)
      }
    }

    return shouldUpdate
  }

  @Suppress("UNCHECKED_CAST")
  fun bind(context: MountContext, content: Any, layoutData: Any?): Any? {
    var binderData: Any? = null
    val hadContinuations = hasContinuations
    currentContinuationContext = context.continuationContext
    beginContinuationVersionRecording()
    var success = false
    try {
      if (context.binderObserver != null) {
        context.binderObserver.observeBind(binderId) {
          binderData = execute { scope ->
            scope.bind(context.androidContext, content, model, layoutData)
          }
        }
      } else {
        binderData = execute { scope ->
          scope.bind(context.androidContext, content, model, layoutData)
        }
      }
      success = true
    } finally {
      finishContinuationVersionRecording(success)
      currentContinuationContext = null
    }
    if (!hadContinuations && hasContinuations) {
      continuationInfo.add(this)
    }
    return binderData
  }

  fun unbind(context: MountContext, content: Any, layoutData: Any?, bindData: Any?) {
    val hadContinuations = hasContinuations
    currentContinuationContext = context.continuationContext
    if (context.binderObserver != null) {
      context.binderObserver.observeUnbind(binderId) {
        execute { scope ->
          scope.unbind(context.androidContext, content, model, layoutData, bindData)
        }
      }
    } else {
      execute { scope ->
        scope.unbind(context.androidContext, content, model, layoutData, bindData)
      }
    }
    currentContinuationContext = null
    continuations = null
    accessedVersions = null
    if (hadContinuations) {
      continuationInfo.remove(this)
    }
  }

  override fun <R> useContinuation(cont: MountContinuation<R>): R {
    // invoke the continuation immediately to ensure that its return value is available within the
    // caller's scope
    val context =
        checkNotNull(currentContinuationContext) {
          "useContinuation called outside of a bind/unbind call on ${binder.description}"
        }
    val previousRecorder = context.currentRecorder
    context.currentRecorder = this
    val value =
        try {
          with(cont) { context.invoke() }
        } finally {
          context.currentRecorder = previousRecorder
        }

    // register the continuation for future execution
    val continuations = this.continuations ?: mutableListOf()
    if (this.continuations == null) {
      this.continuations = continuations
    }

    continuations.add(cont)
    return value
  }

  /** Runs all continuations of this binders with the given [MountContinuationContext] */
  fun restartContinuations(context: MountContinuationContext) {
    val continuations = this.continuations ?: return
    RenderCoreSystrace.beginSection("restartContinuations [${binder.description}]")
    val previousRecorder = context.currentRecorder
    context.currentRecorder = this
    beginContinuationVersionRecording()
    var success = false
    try {
      for (i in continuations.indices) {
        with(continuations[i]) { context.invoke() }
      }
      success = true
    } finally {
      finishContinuationVersionRecording(success)
      context.currentRecorder = previousRecorder
      RenderCoreSystrace.endSection()
    }
  }

  fun transferContinuations(other: BinderHolder) {
    val continuations = this.continuations ?: return
    other.continuations = continuations
    other.accessedVersions = this.accessedVersions
    other.continuationInfo.add(other)
  }

  private inline fun <T> execute(
      func: RenderUnit.Binder<Any?, Any, Any>.(BinderScope) -> T,
  ): T = with(binder) { func(this@BinderHolder) }
}

private class ContinuationInfo {
  private var holders: MutableScatterSet<BinderHolder>? = null

  fun add(holder: BinderHolder) {
    if (!holder.hasContinuations) {
      return
    }

    val holders = ensureHolders()
    holders.add(holder)
  }

  fun remove(holder: BinderHolder) {
    holders?.remove(holder)
  }

  fun restartContinuations(context: MountContinuationContext) {
    val holders = this.holders ?: return
    holders.forEach { holder -> holder.restartContinuations(context) }
  }

  fun hasAnyContinuations(): Boolean = holders != null && holders?.isNotEmpty() == true

  fun hasNewContinuationValues(context: MountContinuationContext): Boolean {
    val holders = this.holders ?: return false
    holders.forEach { holder ->
      if (holder.hasNewContinuationValues(context)) {
        return true
      }
    }
    return false
  }

  private fun ensureHolders(): MutableScatterSet<BinderHolder> {
    return holders ?: MutableScatterSet<BinderHolder>().also { holders = it }
  }
}

interface BinderScope {
  val binderId: BinderId
  val binderModel: Any?

  /**
   * Registers a [MountContinuation] for the current render unit [binder][RenderUnit.Binder] that is
   * being applied in mount. This is only meant to be used within the context of render unit binders
   */
  fun <R> useContinuation(cont: MountContinuation<R>): R
}
