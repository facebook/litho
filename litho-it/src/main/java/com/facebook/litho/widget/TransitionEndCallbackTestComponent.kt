class TransitionEndCallbackTestComponent(
    private val caller: Caller,
    private val testPropForRenderData: String = DEFAULT_TEST_PROP,
) : KComponent() {

  override fun ComponentScope.render(): Component? {
    caller.set(context)

    val state = useState { false }

    useEffect(caller, state) {
      caller.stateGetter = { state.value }
      caller.stateUpdater = { state.update { !it } }

      onCleanup {
        caller.stateGetter = null
        caller.stateUpdater = null
      }
    }

    useTransition(state.value, testPropForRenderData) {
      val onTransitionEndSameKey =
          eventHandler<TransitionEndEvent> { event ->
            if (event.property === AnimatedProperties.X) {
              caller.transitionEndMessage = ANIM_X
            } else {
              caller.transitionEndMessage = ANIM_ALPHA
            }
          }

      val onTransitionEndDisappear =
          eventHandler<TransitionEndEvent> { event ->
            val currentState = caller.stateGetter?.invoke() ?: false
            caller.transitionEndMessage = if (!currentState) ANIM_DISAPPEAR else ""
          }

      val onTransitionEndAuto =
          eventHandler<TransitionEndEvent> { event ->
            caller.transitionEndMessage = ANIM_AUTO
            caller.lastTransitionKey = event.transitionKey
          }

      when (caller.testType) {
        TestType.SAME_KEY -> {
          Transition.parallel(
              Transition.create(TRANSITION_KEY)
                  .animate(AnimatedProperties.ALPHA)
                  .animator(Transition.timing(100))
                  .transitionEndHandler(onTransitionEndSameKey),
              Transition.create(TRANSITION_KEY)
                  .animate(AnimatedProperties.X)
                  .animator(Transition.timing(200))
                  .transitionEndHandler(onTransitionEndSameKey),
          )
        }
        TestType.DISAPPEAR -> {
          Transition.create(Transition.TransitionKeyType.LOCAL, TRANSITION_KEY)
              .animate(AnimatedProperties.SCALE)
              .appearFrom(0f)
              .disappearTo(0f)
              .transitionEndHandler(onTransitionEndDisappear)
        }
        TestType.AUTOGENERATED -> {
          Transition.allLayout()
              .animator(Transition.timing(100))
              .transitionEndHandler(onTransitionEndAuto)
        }
        else -> null
      }
    }

    return when (caller.testType) {
      TestType.SAME_KEY -> getSameKeyTestComponent(state.value)
      TestType.DISAPPEAR -> getDisappearComponent(state.value)
      TestType.AUTOGENERATED -> getAutogeneratedComponent(state.value)
      else -> null
    }
  }

  // Keyless component animated via Transition.allLayout(): its transition id is AUTOGENERATED, so
  // its reference is the structural global key object rather than a String.
  private fun ComponentScope.getAutogeneratedComponent(state: Boolean): Component = Column {
    child(
        Column(style = Style.alignSelf(if (!state) YogaAlign.FLEX_START else YogaAlign.FLEX_END)) {
          child(Row(style = Style.height(50.dp).width(50.dp).backgroundColor(Color.RED)))
        },
    )
  }

  private fun ComponentScope.getDisappearComponent(state: Boolean): Component = Column {
    child(Row(style = Style.height(50.dp).width(50.dp).backgroundColor(Color.YELLOW)))
    child(
        if (!state)
            key(TRANSITION_KEY) {
              Row(
                  style =
                      Style.height(50.dp)
                          .width(50.dp)
                          .backgroundColor(Color.RED)
                          .transitionKey(context, TRANSITION_KEY),
              )
            }
        else null,
    )
  }

  private fun ComponentScope.getSameKeyTestComponent(state: Boolean): Component = Column {
    child(
        Column(style = Style.alignSelf(if (!state) YogaAlign.FLEX_START else YogaAlign.FLEX_END)) {
          child(
              Row(
                  style =
                      Style.height(50.dp)
                          .width(50.dp)
                          .backgroundColor(Color.RED)
                          .alpha(if (!state) 1.0f else 0.2f)
                          .transitionKey(context, TRANSITION_KEY),
              ),
          )
        },
    )
  }

  enum class TestType {
    SAME_KEY,
    DISAPPEAR,
    AUTOGENERATED,
  }

  class Caller {
    var c: ComponentContext? = null
    var transitionEndMessage: String = ""
    var lastTransitionKey: Any? = null
    var testType: TestType? = null
    internal var stateUpdater: (() -> Unit)? = null
    internal var stateGetter: (() -> Boolean)? = null

    fun set(c: ComponentContext?) {
      this.c = c
    }

    fun toggle() {
      stateUpdater?.invoke()
    }
  }

  companion object {
    private const val TRANSITION_KEY = "TRANSITION_KEY"
    const val ANIM_X = "ANIM_X"
    const val ANIM_ALPHA = "ANIM_ALPHA"
    const val ANIM_DISAPPEAR = "ANIM_DISAPPEAR"
    const val ANIM_AUTO = "ANIM_AUTO"
    const val DEFAULT_TEST_PROP = "default"
  }
}
