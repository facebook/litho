package com.facebook.litho

import com.facebook.litho.config.ComponentsConfiguration
import com.facebook.litho.config.ComponentsConfiguration.LogicViolationPolicy
import com.facebook.litho.layout.flexbox.Column
import com.facebook.litho.testing.LithoTestRule
import com.facebook.litho.testing.testrunner.LithoTestRunner
import java.util.concurrent.atomic.AtomicReference
import org.assertj.core.api.Assertions.assertThat
import org.assertj.core.api.Assertions.assertThatCode
import org.assertj.core.api.Assertions.assertThatThrownBy
import org.junit.Rule
import org.junit.Test
import org.junit.runner.RunWith

/**
 * Tests the wrong-context assertion performed by the `reference`-taking state update overloads on
 * [ComponentContext] (generated by the Spec annotation processor). Mirrors the analogous check in
 * [ComponentContext.createEventHandler].
 */
@RunWith(LithoTestRunner::class)
class StateUpdateWrongContextTest {
  @Rule @JvmField val lithoTestRule = LithoTestRule()

  @Test
  fun `state update with wrong component context throws when policy is CRASH`() {
    val context = renderWithPolicy(LogicViolationPolicy.CRASH)

    assertThatThrownBy {
          context.updateStateAsync(
              StateContainer.StateUpdate(0),
              "attribution",
              WrongComponent::class.java,
          )
        }
        .isInstanceOf(IllegalStateException::class.java)
        .hasMessageContaining("belongs to")
  }

  @Test
  fun `state update with correct component context does not throw when policy is CRASH`() {
    val context = renderWithPolicy(LogicViolationPolicy.CRASH)

    assertThatCode {
      context.updateStateAsync(
          StateContainer.StateUpdate(0),
          "attribution",
          ScopeCapturingComponent::class.java,
      )
    }
        .doesNotThrowAnyException()
  }

  @Test
  fun `state update with wrong component context does not throw when policy is LOG`() {
    val context = renderWithPolicy(LogicViolationPolicy.LOG)

    assertThatCode {
      context.updateStateAsync(
          StateContainer.StateUpdate(0),
          "attribution",
          WrongComponent::class.java,
      )
    }
        .doesNotThrowAnyException()
  }

  /**
   * Renders a component with the given [stateUpdateViolationPolicy] and returns the component's
   * scoped [ComponentContext] — the one a generated state update method would receive. Also asserts
   * the scope was captured so the wrong-context check is actually exercised.
   */
  private fun renderWithPolicy(policy: LogicViolationPolicy): ComponentContext {
    val config = ComponentsConfiguration.defaultInstance.copy(stateUpdateViolationPolicy = policy)
    val componentTree =
        ComponentTree.create(lithoTestRule.context).componentsConfiguration(config).build()

    val contextRef = AtomicReference<ComponentContext>()
    lithoTestRule.render(componentTree = componentTree) { ScopeCapturingComponent(contextRef) }

    val context =
        checkNotNull(contextRef.get()) { "Scoped ComponentContext was not captured during render" }
    assertThat(context.componentScope).isInstanceOf(ScopeCapturingComponent::class.java)
    return context
  }
}

private class ScopeCapturingComponent(private val contextRef: AtomicReference<ComponentContext>) :
    KComponent() {
  override fun ComponentScope.render(): Component {
    contextRef.set(context)
    return Column()
  }
}

private class WrongComponent : KComponent() {
  override fun ComponentScope.render(): Component = Column()
}
