package com.facebook.litho

import com.facebook.litho.testing.testrunner.LithoTestRunner
import com.facebook.rendercore.transitions.TransitionUtils
import java.lang.IllegalArgumentException
import org.assertj.core.api.Assertions.assertThat
import org.junit.Test
import org.junit.runner.RunWith

@RunWith(LithoTestRunner::class)
class TransitionUtilsTest {

  private val globalKey = "global-key"
  private val transitionKey = "transition-key"
  private val transitionOwnerKey = "transition-owner-key"

  @Test
  fun noTransitionKeyTest() {
    val id =
        TransitionUtils.createTransitionId(
            null,
            Transition.DEFAULT_TRANSITION_KEY_TYPE,
            transitionOwnerKey,
            globalKey,
        )
    assertThat(id).isNotNull
    assertThat(id?.type).isEqualTo(TransitionId.Type.AUTOGENERATED)
  }

  @Test
  fun defaultTransitionKeyTest() {
    val id =
        TransitionUtils.createTransitionId(
            transitionKey,
            Transition.DEFAULT_TRANSITION_KEY_TYPE,
            transitionOwnerKey,
            globalKey,
        )
    assertThat(id).isNotNull
    assertThat(id?.type).isEqualTo(TransitionId.Type.SCOPED)
    assertThat(id?.reference).isEqualTo(transitionKey)
    assertThat(id?.extraData).isEqualTo(transitionOwnerKey)
  }

  @Test
  fun globalTransitionKeyTest() {
    val id =
        TransitionUtils.createTransitionId(
            transitionKey,
            Transition.TransitionKeyType.GLOBAL,
            transitionOwnerKey,
            globalKey,
        )
    assertThat(id).isNotNull
    assertThat(id?.type).isEqualTo(TransitionId.Type.GLOBAL)
    assertThat(id?.reference).isEqualTo(transitionKey)
  }

  @Test
  fun localTransitionKeyTest() {
    val id =
        TransitionUtils.createTransitionId(
            transitionKey,
            Transition.TransitionKeyType.LOCAL,
            transitionOwnerKey,
            globalKey,
        )
    assertThat(id).isNotNull
    assertThat(id?.type).isEqualTo(TransitionId.Type.SCOPED)
    assertThat(id?.reference).isEqualTo(transitionKey)
    assertThat(id?.extraData).isEqualTo(transitionOwnerKey)
  }

  @Test(expected = IllegalArgumentException::class)
  fun unhandledTransitionKeyTypeTest() {
    TransitionUtils.createTransitionId(transitionKey, null, transitionOwnerKey, globalKey)
  }

  @Test
  fun autogeneratedId_carriesKeyObjectAsReferenceWithoutStringifying() {
    var toStringCount = 0
    val key =
        object {
          override fun toString(): String {
            toStringCount++
            return "built-key"
          }
        }
    val id =
        TransitionUtils.createTransitionId(null, Transition.DEFAULT_TRANSITION_KEY_TYPE, null, key)

    // The reference IS the key object; its (potentially O(depth^2)) String form is never built.
    assertThat(id?.reference).isSameAs(key)
    assertThat(toStringCount).isEqualTo(0)
  }

  @Test
  fun autogeneratedIds_compareByKeyIdentityNotByString() {
    val a1 = autogeneratedId(StructuralKeyStub("A"))
    val a2 = autogeneratedId(StructuralKeyStub("A"))
    val b = autogeneratedId(StructuralKeyStub("B"))

    assertThat(a1).isEqualTo(a2)
    assertThat(a1.hashCode()).isEqualTo(a2.hashCode())
    assertThat(a1).isNotEqualTo(b)
  }

  private fun autogeneratedId(key: Any): TransitionId = checkNotNull(
      TransitionUtils.createTransitionId(
          null,
          Transition.DEFAULT_TRANSITION_KEY_TYPE,
          null,
          key,
      ),
  )

  /** Stub for a structural global key: equals/hashCode by [name], with an "expensive" toString. */
  private class StructuralKeyStub(private val name: String) {
    override fun equals(other: Any?): Boolean = other is StructuralKeyStub && other.name == name

    override fun hashCode(): Int = name.hashCode()

    override fun toString(): String = "expensive($name)"
  }
}
