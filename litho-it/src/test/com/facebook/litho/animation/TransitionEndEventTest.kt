package com.facebook.litho.animation

import com.facebook.litho.testing.LithoTestRule
import com.facebook.litho.testing.TransitionTestRule
import com.facebook.litho.testing.testrunner.LithoTestRunner
import com.facebook.litho.widget.TransitionEndCallbackTestComponent
import org.assertj.core.api.Assertions
import org.junit.Rule
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.annotation.LooperMode

@LooperMode(LooperMode.Mode.LEGACY)
@RunWith(LithoTestRunner::class)
class TransitionEndEventTest {

  @JvmField @Rule val lithoTestRule = LithoTestRule()
  @JvmField @Rule val transitionTestRule = TransitionTestRule()

  @Test
  fun transitionEnCallback_parallelCallback_shouldShowDifferentMessages() {
    val stateUpdater =
        TransitionEndCallbackTestComponent.Caller().apply {
          testType = TransitionEndCallbackTestComponent.TestType.SAME_KEY
        }
    val component = TransitionEndCallbackTestComponent(caller = stateUpdater)

    lithoTestRule.render { component }
    lithoTestRule.idle()

    Assertions.assertThat(stateUpdater.transitionEndMessage)
        .describedAs("Before starting animations")
        .isNullOrEmpty()

    stateUpdater.toggle()
    lithoTestRule.idle()
    transitionTestRule.step(10)
    Assertions.assertThat(stateUpdater.transitionEndMessage)
        .describedAs("Message changed after first transition ended")
        .isEqualTo(TransitionEndCallbackTestComponent.ANIM_ALPHA)

    transitionTestRule.step(20)
    Assertions.assertThat(stateUpdater.transitionEndMessage)
        .describedAs("Message changed after second transition ended")
        .isEqualTo(TransitionEndCallbackTestComponent.ANIM_X)
  }

  @Test
  fun transitionEnCallback_disappearAnimation_shouldDisappearMessage() {
    val stateUpdater =
        TransitionEndCallbackTestComponent.Caller().apply {
          testType = TransitionEndCallbackTestComponent.TestType.DISAPPEAR
        }
    val component = TransitionEndCallbackTestComponent(caller = stateUpdater)

    lithoTestRule.render { component }
    lithoTestRule.idle()

    Assertions.assertThat(stateUpdater.transitionEndMessage)
        .describedAs("Before starting animations")
        .isNullOrEmpty()

    transitionTestRule.step(1000)
    stateUpdater.toggle()
    lithoTestRule.idle()
    transitionTestRule.step(1000)
    Assertions.assertThat(stateUpdater.transitionEndMessage)
        .describedAs("Message changed after disappear transition ended")
        .isEqualTo(TransitionEndCallbackTestComponent.ANIM_DISAPPEAR)
  }

  /**
   * Regression test for P2395250634: a keyless component animated via [Transition.allLayout] gets
   * an AUTOGENERATED transition id whose `reference` is a structural global key object (not a
   * String). The transition-end callback must still be delivered (with the key's String form)
   * instead of crashing with an NPE.
   */
  @Test
  fun transitionEndCallback_autogeneratedKeylessComponent_deliversEventWithoutCrashing() {
    val caller =
        TransitionEndCallbackTestComponent.Caller().apply {
          testType = TransitionEndCallbackTestComponent.TestType.AUTOGENERATED
        }
    val component = TransitionEndCallbackTestComponent(caller = caller)

    lithoTestRule.render { component }
    lithoTestRule.idle()

    Assertions.assertThat(caller.transitionEndMessage)
        .describedAs("Before starting animations")
        .isNullOrEmpty()

    caller.toggle()
    lithoTestRule.idle()
    transitionTestRule.step(50)

    Assertions.assertThat(caller.transitionEndMessage)
        .describedAs("End handler fires for a keyless (AUTOGENERATED) component without an NPE")
        .isEqualTo(TransitionEndCallbackTestComponent.ANIM_AUTO)
    Assertions.assertThat(caller.lastTransitionKey)
        .describedAs("AUTOGENERATED transitionKey is delivered as the raw structural global key")
        .isNotNull()
  }
}
