package com.facebook.litho

import androidx.annotation.IntDef

/**
 * Represents a unique id used for transitions, that is assigned to [AnimatableItem] based on
 * [com.facebook.rendercore.Node]'s transitionKey and transitionKeyType, later passed on to a
 * [com.facebook.rendercore.MountItem], and used by
 * [com.facebook.rendercore.MountDelegate.MountDelegateTarget] and [TransitionManager]
 */
class TransitionId(
    @field:Type @JvmField val type: Int,
    /**
     * The id's identity. For [Type.GLOBAL]/[Type.SCOPED] the transition-key String; for
     * [Type.AUTOGENERATED] the component's structural global key (compared by object, not its
     * String form).
     */
    @JvmField val reference: Any?,
    /** The owner's global key for [Type.SCOPED] ids; `null` otherwise. */
    @JvmField val extraData: Any?,
) {

  @IntDef(Type.GLOBAL, Type.SCOPED, Type.AUTOGENERATED)
  @Retention(AnnotationRetention.SOURCE)
  annotation class Type {
    companion object {
      const val GLOBAL = 1
      const val SCOPED = 2
      const val AUTOGENERATED = 3
    }
  }

  private val _hashCode: Int =
      (reference?.hashCode() ?: 0) * 31 * 31 + (extraData?.hashCode() ?: 0) * 31 + type

  override fun equals(other: Any?): Boolean {
    if (this === other) {
      return true
    }

    if (other == null || javaClass != other.javaClass) {
      return false
    }

    val that = other as TransitionId
    return type == that.type && reference == that.reference && extraData == that.extraData
  }

  override fun hashCode(): Int = _hashCode

  override fun toString(): String {
    val sb = StringBuilder()
    sb.append("TransitionId{")
    sb.append("\"").append(reference).append("\", ")
    when (type) {
      Type.GLOBAL -> sb.append("GLOBAL")
      Type.SCOPED -> sb.append("SCOPED(").append(extraData).append(")")
      Type.AUTOGENERATED -> sb.append("AUTOGENERATED")
    }
    sb.append("}")
    return sb.toString()
  }

  companion object {
    /** Creates a [Type.AUTOGENERATED] id identified by the structural global [key]. */
    @JvmStatic
    fun autogenerated(key: Any): TransitionId = TransitionId(Type.AUTOGENERATED, key, null)
  }
}
