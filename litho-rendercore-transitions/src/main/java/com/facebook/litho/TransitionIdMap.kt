package com.facebook.litho

/**
 * An object that maps [TransitionId]s to values. It keeps track of TransitionId types, thus
 * allowing efficient look for keys of a particular type.
 *
 * This is important for [TransitionManager] that needs to map [TransitionId]s to
 * [TransitionManager.AnimationState]s, and quickly find a value when creating transition for the
 * given
 * [Transition.TransitionUnit] - [TransitionManager#createAnimationsForTransitionUnit(Transition.TransitionUnit)]
 */
internal class TransitionIdMap<V> {

  // Keyed by id.reference: the transition-key String for GLOBAL/SCOPED, the structural global key
  // object for AUTOGENERATED (write-only set, never looked up).
  private val globalIds: MutableMap<Any, TransitionId> = LinkedHashMap()
  private val scopedIdsByOwner: MutableMap<Any?, MutableMap<Any, TransitionId>> = LinkedHashMap()
  private val autogeneratedIds: MutableMap<Any, TransitionId> = LinkedHashMap()

  private val _ids: MutableMap<TransitionId, V> = HashMap()

  /**
   * Checks if this map contains a mapping for the specified [TransitionId].
   *
   * @param id [TransitionId] whose presence in this map is to be tested
   * @return `true` if this map contains a mapping for the specified key
   */
  fun contains(id: TransitionId): Boolean = _ids.containsKey(id)

  /**
   * Associates the specified value with the specified [TransitionId] in this map. If the map
   * previously contained a mapping for the key, the old value is replaced by the specified value.
   *
   * @param id [TransitionId] with which the specified value is to be associated
   * @param value value to be associated with the specified [TransitionId]
   */
  fun put(id: TransitionId, value: V) {
    if (_ids.put(id, value) == null) {
      // New transition id for this set
      when (id.type) {
        TransitionId.Type.GLOBAL -> globalIds[checkNotNull(id.reference)] = id
        TransitionId.Type.SCOPED -> {
          val owner = id.extraData
          var siblingsIds = scopedIdsByOwner[owner]
          if (siblingsIds == null) {
            siblingsIds = LinkedHashMap()
            scopedIdsByOwner[owner] = siblingsIds
          }
          siblingsIds[checkNotNull(id.reference)] = id
        }

        TransitionId.Type.AUTOGENERATED -> autogeneratedIds[checkNotNull(id.reference)] = id
        else -> throw RuntimeException("Unknown TransitionId type ${id.type}")
      }
    }
  }

  /**
   * Returns the value to which the specified [TransitionId] is mapped, or `null` if this map
   * contains no mapping for the key.
   *
   * @see [put]
   */
  operator fun get(id: TransitionId?): V? = _ids[id]

  /**
   * Removes the mapping for the specified [TransitionId] from this map if present.
   *
   * @param id [TransitionId] whose mapping is to be removed from the map
   */
  fun remove(id: TransitionId) {
    if (_ids.remove(id) == null) {
      // There is no mapping for the id, return early
      return
    }

    when (id.type) {
      TransitionId.Type.GLOBAL -> globalIds.remove(checkNotNull(id.reference))
      TransitionId.Type.SCOPED -> {
        val owner = id.extraData
        val siblingsIds = scopedIdsByOwner[owner]
        if (siblingsIds != null) {
          siblingsIds.remove(checkNotNull(id.reference))
          if (siblingsIds.isEmpty()) {
            scopedIdsByOwner.remove(owner)
          }
        }
      }

      TransitionId.Type.AUTOGENERATED -> autogeneratedIds.remove(checkNotNull(id.reference))
    }
  }

  /**
   * Returns a [TransitionId] of type [TransitionId.Type.GLOBAL] with the specified reference if
   * this map contains mapping for such [TransitionId], or `null` otherwise.
   */
  fun getGlobalId(reference: String?): TransitionId? =
      if (reference != null) globalIds[reference] else null

  /**
   * Returns a [TransitionId] of type [TransitionId.Type.SCOPED] with the specified owner and
   * reference if this map contains mapping for such [TransitionId], or `null` otherwise.
   */
  fun getScopedId(owner: Any?, reference: String?): TransitionId? {
    if (reference == null) return null
    val siblingsIds: Map<Any, TransitionId>? = scopedIdsByOwner[owner]
    return siblingsIds?.get(reference)
  }

  /** Returns a [Set] view of the [TransitionId]s mappings for which are contained in this map. */
  fun ids(): Set<TransitionId> = _ids.keys

  /** Returns a [Collection] view of the values contained in this map. */
  fun values(): Collection<V> = _ids.values

  /** Removes all of the mappings from this map. */
  fun clear() {
    globalIds.clear()
    scopedIdsByOwner.clear()
    autogeneratedIds.clear()

    _ids.clear()
  }
}
